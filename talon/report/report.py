"""Render a scan into a Markdown report and a machine-readable JSON file."""
from __future__ import annotations

import json
import time
from dataclasses import asdict

from ..agent import ScanResult
from ..checks.base import Finding

_SEV_EMOJI = {
    "Critical": "🟥", "High": "🟧", "Medium": "🟨", "Low": "🟦", "None": "⬜",
}


def _summary_with_llm(result: ScanResult) -> str | None:
    llm = None
    # The agent stashes the LLM on itself; summary is best-effort.
    try:
        from ..llm import LLM
        llm = LLM()
    except Exception:
        return None
    if not llm.enabled or not result.validated:
        return None
    lines = [f"- {f.name} ({f.severity} {f.cvss_score}) at {f.url} param {f.parameter}"
             for f in result.validated]
    system = (
        "You are a penetration tester writing the executive summary of a "
        "security assessment. Be concise, factual, business-impact focused. "
        "2-4 sentences. No markdown headings."
    )
    return llm.complete(system, "Validated findings:\n" + "\n".join(lines), max_tokens=300)


def to_markdown(result: ScanResult) -> str:
    gen = time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime())
    dur = result.finished - result.started
    out: list[str] = []
    a = out.append

    a(f"# Talon Security Assessment")
    a("")
    a(f"- **Targets:** {', '.join(result.targets)}")
    a(f"- **In-scope hosts:** {', '.join(sorted(result.scope.allowed_hosts))}")
    a(f"- **Generated:** {gen}")
    a(f"- **Surfaces tested:** {result.surfaces_tested} "
      f"| **Requests:** {result.requests_made} "
      f"| **Duration:** {dur:.1f}s")
    a(f"- **LLM brain:** {'yes' if result.llm_used else 'no (deterministic)'}")
    a(f"- **Crawl mode:** {'rendered — ' + str(result.rendered) + ' page(s) via headless browser' if result.rendered else 'raw HTML (stdlib)'}")
    if result.budget_exhausted:
        a("- **⚠️ Partial scan:** the request budget was exhausted before all "
          "surfaces were tested. Re-run with a higher `--max-requests`.")
    a("")
    a("> **Authorized testing only.** This report documents issues Talon could "
      "reproduce against the scoped targets. Every *validated* finding below "
      "includes a proof-of-concept request. CVSS vectors are base scores and a "
      "starting point for the analyst to refine.")
    a("")

    summary = _summary_with_llm(result)
    if summary:
        a("## Executive summary")
        a("")
        a(summary.strip())
        a("")

    # Findings table
    a("## Findings at a glance")
    a("")
    if not result.validated and not result.probable:
        a("_No issues detected in the tested surface._")
        a("")
    else:
        a("| # | Severity | CVSS | Type | Location | Confidence |")
        a("|---|----------|------|------|----------|------------|")
        n = 1
        for f in result.validated + result.probable:
            emoji = _SEV_EMOJI.get(f.severity, "")
            loc = f.url + (f" (`{f.parameter}`)" if f.parameter else "")
            a(f"| {n} | {emoji} {f.severity} | {f.cvss_score} | {f.name} "
              f"| {loc} | {f.confidence} |")
            n += 1
        a("")

    if result.validated:
        a("## Validated findings (with proof-of-concept)")
        a("")
        for i, f in enumerate(result.validated, 1):
            _render_finding(a, i, f)

    if result.probable:
        a("## Probable findings (manual review recommended)")
        a("")
        a("_These showed a strong signal but were not fully proven by Talon. "
          "No PoC is claimed; confirm manually before reporting._")
        a("")
        for i, f in enumerate(result.probable, 1):
            _render_finding(a, i, f, probable=True)

    # Attack-surface inventory — what Talon actually tested (shown even when
    # there are no findings, so a clean run is still legible).
    if result.surfaces:
        a("## Attack surface tested")
        a("")
        a(f"Talon probed {len(result.surfaces)} surface(s). A clean run means none "
          f"of the three checks could prove an issue on these inputs.")
        a("")
        a("| Method | URL | Parameters |")
        a("|--------|-----|------------|")
        for s in result.surfaces:
            ps = ", ".join(f"`{p}`" for p in s["params"]) or "—"
            enc = s.get("encoding", "query")
            tag = s["method"] + (f" ({enc})" if s["method"] == "POST" else "")
            a(f"| {tag} | {s['url']} | {ps} |")
        a("")

    # Agent reasoning trace (transparency)
    a("## Agent trace")
    a("")
    a("```")
    for line in result.reasoning:
        a(line)
    a("```")
    a("")
    a("---")
    a(f"_Generated by Talon v0.1 — validation-first web vulnerability agent._")
    return "\n".join(out)


def _render_finding(a, i: int, f: Finding, *, probable: bool = False) -> None:
    emoji = _SEV_EMOJI.get(f.severity, "")
    a(f"### {i}. {f.name} — {emoji} {f.severity} (CVSS {f.cvss_score})")
    a("")
    a(f"- **URL:** {f.url}")
    if f.parameter:
        a(f"- **Parameter:** `{f.parameter}`")
    a(f"- **CWE:** {f.cwe or 'n/a'}")
    a(f"- **CVSS 3.1:** `{f.cvss_vector}` → {f.cvss_score} ({f.severity})")
    a("")
    a(f"**Description.** {f.description}")
    a("")
    a(f"**Evidence.** {f.evidence}")
    a("")
    a("**Proof of concept.**")
    a("")
    a("```http")
    a(f.poc)
    a("```")
    a("")
    a(f"**Remediation.** {f.remediation}")
    a("")
    if f.exchanges:
        ex = f.exchanges[-1]
        resp = ex.response
        a("<details><summary>Recorded response (excerpt)</summary>")
        a("")
        a("```")
        a(f"HTTP {resp.status}")
        for k in ("content-type", "location", "set-cookie"):
            v = resp.header(k)
            if v:
                a(f"{k}: {v}")
        body = (resp.body or "")[:400]
        a("")
        a(body)
        a("```")
        a("</details>")
        a("")
    a("---")
    a("")


def to_json(result: ScanResult) -> str:
    def finding_dict(f: Finding) -> dict:
        d = asdict(f)
        d.pop("exchanges", None)  # not JSON-trivial; keep report lean
        return d

    payload = {
        "tool": "talon",
        "version": "0.1.0",
        "targets": result.targets,
        "scope_hosts": sorted(result.scope.allowed_hosts),
        "generated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "stats": {
            "surfaces_tested": result.surfaces_tested,
            "requests_made": result.requests_made,
            "duration_s": round(result.finished - result.started, 2),
            "llm_used": result.llm_used,
            "budget_exhausted": result.budget_exhausted,
            "pages_rendered": result.rendered,
        },
        "attack_surface": result.surfaces,
        "validated": [finding_dict(f) for f in result.validated],
        "probable": [finding_dict(f) for f in result.probable],
        "reasoning": result.reasoning,
    }
    return json.dumps(payload, indent=2)
